"""One command, whole story: python scripts/demo.py

Day 1 initial load -> day 2 incremental -> consent stream -> audiences -> activation export
-> RAG index -> the questions an AI assistant would ask through MCP. Writes a readable
transcript to docs/demo_output.md so reviewers can see results without running Spark.
"""
from __future__ import annotations

import json
import os
import shutil
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
os.environ.setdefault("TZ", "UTC")
if hasattr(time, "tzset"):
    time.tzset()

from tlake import activate, audience, generate, governance, mcp_server, pipeline, settings  # noqa: E402
from tlake.rag import ingest, retrieve  # noqa: E402

out: list[str] = []


def say(md: str = ""):
    print(md)
    out.append(md)


def block(obj):
    say("```json\n" + json.dumps(obj, indent=2, default=str) + "\n```")


def main():
    for d in (settings.LAKE, settings.SOURCES, settings.EXPORTS):
        shutil.rmtree(d, ignore_errors=True)
    t0 = time.time()
    say("# Demo output\n\nGenerated by `python scripts/demo.py` on synthetic data (fictional partners and people).\n")

    say("## 1. Day 1: initial load of three partner databases")
    block(generate.generate(1))
    r1 = pipeline.run()
    block({"silver": r1["silver"], "gold": r1["gold"], "consent_stream": r1["consent_stream"],
           "dq_findings": [f"{d['entity']}.{d['rule']} ({d['severity']}): {d['failed']}" for d in r1["dq_failures"]],
           "seconds": r1["seconds"]})

    say("## 2. Day 2: incremental changes (tier changes, late members, cancellations, opt-outs)")
    block(generate.generate(2))
    r2 = pipeline.run()
    block({"bronze_rows_pulled": {e["source"]: e["rows"] for e in r2["bronze"]},
           "silver": r2["silver"], "consent_stream": r2["consent_stream"], "seconds": r2["seconds"]})

    say("## 3. Consent-aware audiences (marketing writes YAML, platform enforces the law)")
    for spec in sorted((ROOT / "config/campaigns").glob("*.yaml")):
        block(audience.build(spec))

    say("## 4. Activation export (marketing_ops only; consent re-checked at export time)")
    block(audience.export("SAM-CRZ-CARIB-27Q1", "user:mops.sam"))
    try:
        audience.export("SAM-CRZ-CARIB-27Q1", "user:analyst.bhb")
    except governance.AccessDenied as e:
        say(f"Analyst attempt -> `AccessDenied: {e}`\n")

    say("## 4b. Automations: sync the consented audience to Marketo and Tealium (dry run)")
    say("Opt-outs are pushed to Marketo as `unsubscribed`, the static list is synced to exactly the consented "
        "audience, and Tealium gets each member as a hashed-email audience event. Without credentials "
        "nothing leaves the machine; the exact requests are written to `exports/integrations/`.\n")
    block(activate.activate("SAM-CRZ-CARIB-27Q1", "user:mops.sam"))

    say("## 5. RAG index over brand guidelines and policy docs")
    block(ingest.build_index())

    say("## 6. What an AI assistant gets through the MCP server")
    os.environ["TLAKE_PRINCIPAL"] = "agent:data-copilot"
    calls = [
        ("data_freshness", {}),
        ("query_metric", {"metric": "gross_booking_value_usd", "group_by": ["partner_code", "product_type"]}),
        ("query_metric", {"metric": "email_click_rate", "group_by": ["campaign_product"]}),
        ("query_metric", {"metric": "web_product_views", "group_by": ["partner_code", "product_type"]}),
        ("estimate_audience", {"partner_code": "SAM", "criteria": {"min_cruise_affinity": 0.3, "countries": ["DE", "FR", "GB"]}}),
        ("describe_dataset", {"name": "dim_member"}),
        ("search_knowledge", {"question": "Can we email members in Germany without an opt-in?"}),
        ("search_knowledge", {"question": "What does the deliverability agency integration request say?"}),
    ]
    for name, args in calls:
        say(f"### `{name}({json.dumps(args)})`  as agent:data-copilot")
        res = getattr(mcp_server, name)(**args)
        if name == "query_metric" and "data" in res:
            res["data"]["rows"] = res["data"]["rows"][:8]
        block(res)

    os.environ["TLAKE_PRINCIPAL"] = "agent:sam-marketing-copilot"
    say("### Same server, deployed for the SAM brand only (`TLAKE_PRINCIPAL=agent:sam-marketing-copilot`)")
    block(mcp_server.estimate_audience("BHB", {"min_cruise_affinity": 0.3}))
    block(mcp_server.query_metric("marketable_members", ["partner_code"]))
    a = retrieve.answer("What disclaimer does BlueHarbor need in emails?", governance.principal("agent:sam-marketing-copilot"))
    say(f"SAM agent asks about BlueHarbor's guidelines -> `{a['answer']}`\n")

    gen = ROOT / "docs/generated"
    gen.mkdir(parents=True, exist_ok=True)
    (gen / "fabric_security.sql").write_text(governance.render_fabric_sql(), encoding="utf-8")
    say(f"Generated `docs/generated/fabric_security.sql`. Total demo time {time.time() - t0:.0f}s.")
    (ROOT / "docs/demo_output.md").write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
